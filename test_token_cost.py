
import os
import json

from dotenv import load_dotenv
from openai import OpenAI
from pydantic import BaseModel, ConfigDict, Field


# Step 1: Load environment variables
load_dotenv()

api_key = os.getenv("GROQ_API_KEY")

if not api_key:
    raise ValueError("GROQ_API_KEY not found in .env")


# Step 2: Define the expected response structure
class BusinessInsight(BaseModel):

    model_config = ConfigDict(extra="forbid")

    summary: str = Field(
        description="A short business summary"
    )

    key_points: list[str] = Field(
        description="Important business points"
    )

    recommendation: str = Field(
        description="One business recommendation"
    )


# Step 3: Connect to Groq
client = OpenAI(
    api_key=api_key,
    base_url="https://api.groq.com/openai/v1",
    max_retries=0,
    timeout=30.0
)


# Step 4: Send a request to Groq
response = client.chat.completions.create(

    model="openai/gpt-oss-20b",

    messages=[
        {
            "role": "system",
            "content": "You are an e-commerce business analyst. Return a structured business insight."
        },
        {
            "role": "user",
            "content": "Explain why businesses should monitor customer order delivery performance."
        }
    ],

    response_format={
        "type": "json_schema",
        "json_schema": {
            "name": "business_insight",
            "strict": True,
            "schema": BusinessInsight.model_json_schema()
        }
    }
)


# Step 5: Validate the response
content = response.choices[0].message.content

if not content:
    raise ValueError("Groq returned an empty response.")

validated_data = BusinessInsight.model_validate(
    json.loads(content)
)


# Step 6: Read actual token usage
usage = response.usage # Get tokens usages from Groq

if usage is None:
    raise ValueError("Token usage information was not returned.")

input_tokens = usage.prompt_tokens # Count tokens sent to Groq
output_tokens = usage.completion_tokens # Count token generated by Groq
total_tokens = usage.total_tokens # Count total tokens used


# Step 7: Check whether any input tokens were cached
prompt_details = getattr(
    usage,
    "prompt_tokens_details",
    None
)

cached_tokens = (
    getattr(prompt_details, "cached_tokens", 0) or 0
) # Checks how many input tokens were cached

regular_input_tokens = input_tokens - cached_tokens


# Step 8: Calculate API cost in USD
INPUT_PRICE = 0.075
CACHED_INPUT_PRICE = 0.0375
OUTPUT_PRICE = 0.30

input_cost = (
    regular_input_tokens * INPUT_PRICE
    + cached_tokens * CACHED_INPUT_PRICE
) / 1_000_000  # Input cost =  calculates the input-token cost

output_cost = (
    output_tokens * OUTPUT_PRICE
) / 1_000_000 # Calculates the output-token cost

total_cost = input_cost + output_cost # Adds both costs


# Step 9: Display the results
print("\nGROQ RESPONSE")
print(json.dumps(validated_data.model_dump(), indent=4))

print("\nTOKEN USAGE")
print("Input tokens:", input_tokens)
print("Output tokens:", output_tokens)
print("Total tokens:", total_tokens)
print("Cached input tokens:", cached_tokens)

print("\nAPI COST")
print(f"Input cost: ${input_cost:.10f}")
print(f"Output cost: ${output_cost:.10f}")
print(f"Total API cost: ${total_cost:.10f}")

print("\nToken usage and cost tracking: PASS")
